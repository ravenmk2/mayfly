// Setup input validation (docs/design/setup.md section 3).
const (
	// MinAdminPasswordLength bounds the console administrator password.
	MinAdminPasswordLength = 8
	// testDBTimeout bounds the wizard's connectivity check.
	testDBTimeout = 5 * time.Second
)

// ErrInvalidSetup marks setup input validation failures; the HTTP layer maps
// them to 400.
var ErrInvalidSetup = errors.New("admin: invalid setup input")

// SetupInput is the wizard submission (docs/design/setup.md section 3).
type SetupInput struct {
	// DBType is sqlite or mysql.
	DBType string
	// DSN is the MySQL driver DSN (mysql only); SQLite stores at
	// <data-dir>/mayfly.db.
	DSN string
	// AdminPassword is the plaintext console administrator password.
	AdminPassword string
}

// validate checks the setup input.
func (in SetupInput) validate() error {
	switch in.DBType {
	case "sqlite":
	case "mysql":
		if in.DSN == "" {
			return fmt.Errorf("%w: mysql dsn is required", ErrInvalidSetup)
		}
	default:
		return fmt.Errorf("%w: db type must be sqlite or mysql, got %q", ErrInvalidSetup, in.DBType)
	}
	if len(in.AdminPassword) < MinAdminPasswordLength {
		return fmt.Errorf("%w: admin_password must be at least %d characters", ErrInvalidSetup, MinAdminPasswordLength)
	}
	return nil
}

// MainDSN resolves the primary database DSN in the "sqlite:<path>" /
// "mysql:<driver-dsn>" form used across the broker.
func (in SetupInput) MainDSN(dataDir string) string {
	if in.DBType == "mysql" {
		return "mysql:" + in.DSN
	}
	return "sqlite:" + filepath.Join(dataDir, "mayfly.db")
}

// setupConfigYAML is the generated mayfly.yaml (docs/design/setup.md section
// 3): the chosen database backs both persistence and the auth chains.
type setupConfigYAML struct {
	DataDir   string `yaml:"data_dir"`
	Listeners []struct {
		Type    string `yaml:"type"`
		Address string `yaml:"address"`
	} `yaml:"listeners"`
	Store struct {
		DSN string `yaml:"dsn"`
	} `yaml:"store"`
	Auth struct {
		Authentication []struct {
			Type string `yaml:"type"`
			DSN  string `yaml:"dsn"`
		} `yaml:"authentication"`
		Authorization []struct {
			Type string `yaml:"type"`
			DSN  string `yaml:"dsn"`
		} `yaml:"authorization"`
	} `yaml:"auth"`
}

// writeConfig renders the generated mayfly.yaml.
func writeConfig(configPath, dataDir, mainDSN string) error {
	var doc setupConfigYAML
	doc.DataDir = dataDir
	doc.Listeners = append(doc.Listeners, struct {
		Type    string `yaml:"type"`
		Address string `yaml:"address"`
	}{Type: "tcp", Address: ":1883"})
	doc.Store.DSN = mainDSN
	doc.Auth.Authentication = append(doc.Auth.Authentication, struct {
		Type string `yaml:"type"`
		DSN  string `yaml:"dsn"`
	}{Type: "db", DSN: mainDSN})
	doc.Auth.Authorization = append(doc.Auth.Authorization, struct {
		Type string `yaml:"type"`
		DSN  string `yaml:"dsn"`
	}{Type: "db", DSN: mainDSN})
	raw, err := yaml.Marshal(doc)
	if err != nil {
		return fmt.Errorf("admin: render config: %w", err)
	}
	header := "# mayfly configuration, generated by the setup wizard (docs/design/setup.md).\n" +
		"# Restart mayfly to activate the MQTT listeners.\n"
	if err := os.WriteFile(configPath, append([]byte(header), raw...), 0o600); err != nil {
		return fmt.Errorf("admin: write %s: %w", configPath, err)
	}
	return nil
}

// PerformSetup executes the installation wizard (docs/design/setup.md
// section 3): it persists the master key, initializes the primary database
// schema (auth tables, then the admin tables), creates the console
// administrator and writes mayfly.yaml. The HTTP endpoint and the
// MAYFLY_SETUP_* non-interactive path share it.
func PerformSetup(ctx context.Context, dataDir, configPath string, in SetupInput, logger *slog.Logger) ([]byte, error) {
	if err := in.validate(); err != nil {
		return nil, err
	}
	if err := os.MkdirAll(dataDir, 0o750); err != nil {
		return nil, fmt.Errorf("admin: create data dir: %w", err)
	}
	mainDSN := in.MainDSN(dataDir)

	// Probe the database and apply the auth schema before touching any file:
	// a typo in the DSN must not leave a half-initialized data directory.
	if err := auth.Migrate(ctx, mainDSN); err != nil {
		return nil, fmt.Errorf("admin: initialize primary database schema: %w", err)
	}

	hash, err := hashPassword(in.AdminPassword)
	if err != nil {
		return nil, err
	}
	st, err := OpenSQLStore(mainDSN)
	if err != nil {
		return nil, err
	}
	err = st.CreateUser(ctx, "admin", hash)
	_ = st.Close()
	if errors.Is(err, ErrExists) {
		return nil, fmt.Errorf("%w: console admin already exists", ErrInvalidSetup)
	}
	if err != nil {
		return nil, err
	}

	masterKey, err := WriteMasterKey(dataDir)
	if err != nil {
		return nil, err
	}
	if err := writeConfig(configPath, dataDir, mainDSN); err != nil {
		return nil, err
	}
	logger.Info("setup completed; restart mayfly to start the MQTT listeners",
		"db", in.DBType, "config", configPath)
	return masterKey, nil
}

// setupRequest is the POST /api/v1/setup body.
type setupRequest struct {
	DB struct {
		Type string `json:"type"`
		DSN  string `json:"dsn"`
	} `json:"db"`
	AdminPassword string `json:"admin_password"`
}

// setupStatus answers GET /api/v1/setup/status.
func (s *Server) setupStatus(c echo.Context) error {
	return c.JSON(http.StatusOK, map[string]bool{"initialized": s.isInitialized()})
}

// setupTestDB answers POST /api/v1/setup/test-db: it probes a MySQL DSN
// without persisting anything (docs/design/setup.md section 6).
func (s *Server) setupTestDB(c echo.Context) error {
	var req setupRequest
	if err := c.Bind(&req); err != nil {
		return abort(c, http.StatusBadRequest, "bad_request", "invalid JSON body")
	}
	if req.DB.Type != "mysql" {
		return abort(c, http.StatusBadRequest, "bad_request", "only mysql connections can be tested")
	}
	if req.DB.DSN == "" {
		return abort(c, http.StatusBadRequest, "bad_request", "db.dsn is required")
	}
	db, _, err := auth.OpenDB("mysql:" + req.DB.DSN)
	if err != nil {
		return abort(c, http.StatusBadRequest, "db_unreachable", err.Error())
	}
	defer func() { _ = db.Close() }()
	ctx, cancel := context.WithTimeout(c.Request().Context(), testDBTimeout)
	defer cancel()
	if err := db.PingContext(ctx); err != nil {
		return abort(c, http.StatusBadRequest, "db_unreachable", err.Error())
	}
	return c.JSON(http.StatusOK, map[string]bool{"ok": true})
}

// setup executes the wizard. Once initialized the endpoint answers 410 Gone
// (docs/design/setup.md section 6).
func (s *Server) setup(c echo.Context) error {
	if s.isInitialized() {
		return abort(c, http.StatusGone, "gone", "mayfly is already initialized")
	}
	var req setupRequest
	if err := c.Bind(&req); err != nil {
		return abort(c, http.StatusBadRequest, "bad_request", "invalid JSON body")
	}

	// Serialize concurrent wizard submissions; the first one wins.
	s.setupMu.Lock()
	defer s.setupMu.Unlock()
	if s.isInitialized() {
		return abort(c, http.StatusGone, "gone", "mayfly is already initialized")
	}

	masterKey, err := PerformSetup(c.Request().Context(), s.dataDir, s.configPath,
		SetupInput{DBType: req.DB.Type, DSN: req.DB.DSN, AdminPassword: req.AdminPassword}, s.log)
	if errors.Is(err, ErrInvalidSetup) {
		return abort(c, http.StatusBadRequest, "bad_request", err.Error())
	}
	if err != nil {
		return abort(c, http.StatusBadGateway, "setup_failed", err.Error())
	}
	s.mu.Lock()
	s.masterKey = masterKey
	s.initialized = true
	s.mu.Unlock()
	return c.JSON(http.StatusCreated, map[string]any{
		"initialized":      true,
		"restart_required": true,
	})
}
